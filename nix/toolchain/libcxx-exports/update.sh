#!/usr/bin/env bash
# regenerates the libc++ and libc++abi export lists from the built arm64 dylibs
# usage: update.sh NM LIBCXXABI_DYLIB LIBCXX_DYLIB, NM reading Mach-O (the cross toolchain's arm64-apple-darwin20.4-nm)
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
[ $# -eq 3 ] || { echo "usage: update.sh NM LIBCXXABI_DYLIB LIBCXX_DYLIB" >&2; exit 2; }
nm=$1
syms() {
  "$nm" -gU "$1" | awk '{print $3}' | sort -u
}
hdr='# generated by update.sh from the built dylib, one exported symbol per line, for the sdk tbd'
{ echo "$hdr"; syms "$2"; } > "$here/libc++abi.exports"
{ echo "$hdr"; syms "$3"; } > "$here/libc++.exports"
